//! Rasterises the WhatsApp Web icons in assets/icons/*.svg (24x24 viewBox, copied from the page)
//! into assets/icons.atlas as 8-bit coverage masks, and writes crates/ui/src/icon_ids.rs with the
//! matching `Icon` enum, so the tool and the ui can never disagree about the order.
//!
//! Layout: u8 count, then per icon `u8 size` and `u32 offset` (little endian), then the masks packed
//! like glyphs (`pack` in tools/bakefont, rows of `size` bytes; offsets from the start of the file).
//!
//! Run from the repository root: `cargo run --release -p bakeicons [preview.png]`.

#[path = "../../bakefont/src/pack.rs"]
mod pack;

